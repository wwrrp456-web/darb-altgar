  txt = await L.textContent(); ok(/قراءة السعر والقيمة/.test(txt) && /عمّ سالم/.test(txt), 'درس المستوى ١ بلسان عمّ سالم');
  for (let i = 0; i < 4; i++) { await p.locator('[data-act=lnext]').click(); await p.waitForTimeout(120); }
