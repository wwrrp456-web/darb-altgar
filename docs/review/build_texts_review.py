def rtl_par(p, align=R):
    p._p.get_or_add_pPr().append(OxmlElement('w:bidi')); p.alignment = align


def run(p, text, bold=False, size=None, color=None, italic=False):
    r = p.add_run(text); r.bold = bold; r.italic = italic; r.font.name = FONT
    r._element.get_or_add_rPr().rFonts.set(qn('w:cs'), FONT); r._element.rPr.append(OxmlElement('w:rtl'))
    if size: r.font.size = Pt(size)
    if color is not None: r.font.color.rgb = color
    return r


def para(text='', bold=False, size=None, color=None, after=4, align=R, italic=False):
    p = doc.add_paragraph(); rtl_par(p, align); p.paragraph_format.space_after = Pt(after)
    if text: run(p, text, bold, size, color, italic)
    return p


def heading(text, level=1):
    p = para(text, True, {1: 18, 2: 14, 3: 12}[level], NAVY if level < 3 else MINT, after=6)
    p.paragraph_format.space_before = Pt(12 if level > 1 else 6); p.paragraph_format.keep_with_next = True
    pPr = p._p.get_or_add_pPr(); ol = OxmlElement('w:outlineLvl'); ol.set(qn('w:val'), str(level - 1)); pPr.append(ol)
    return p


def bullet(text, bold_lead=None):
    p = para('', after=3); p.paragraph_format.right_indent = Cm(0.5)
    run(p, '• '); 
    if bold_lead: run(p, bold_lead + ' ', True)
    run(p, text); return p


def shade(cell, hexcolor):
    tcPr = cell._tc.get_or_add_tcPr(); sh = OxmlElement('w:shd'); sh.set(qn('w:val'), 'clear'); sh.set(qn('w:color'), 'auto'); sh.set(qn('w:fill'), hexcolor); tcPr.append(sh)


def borders(tbl, color='B7C3CC'):
    tblPr = tbl._tbl.tblPr; b = OxmlElement('w:tblBorders')
    for e in ('top', 'left', 'bottom', 'right', 'insideH', 'insideV'):
        x = OxmlElement('w:' + e); x.set(qn('w:val'), 'single'); x.set(qn('w:sz'), '4'); x.set(qn('w:space'), '0'); x.set(qn('w:color'), color); b.append(x)
    tblPr.append(b); tblPr.append(OxmlElement('w:bidiVisual'))


def widths(tbl, ws):
    tbl.autofit = False
    tblPr = tbl._tbl.tblPr; lay = OxmlElement('w:tblLayout'); lay.set(qn('w:type'), 'fixed'); tblPr.append(lay)
    for i, w in enumerate(ws): tbl.columns[i].width = Cm(w)
    for row in tbl.rows:
        for i, w in enumerate(ws): row.cells[i].width = Cm(w)


def cell_text(cell, text, bold=False, size=10, color=None, align=R):
    cell.text = ''
    lines = str(text).split('\n')
    for i, ln in enumerate(lines):
        p = cell.paragraphs[0] if i == 0 else cell.add_paragraph()
        rtl_par(p, align); p.paragraph_format.space_after = Pt(1)
        run(p, ln, bold, size, color)


def repeat_header(row):
    trPr = row._tr.get_or_add_trPr(); h = OxmlElement('w:tblHeader'); h.set(qn('w:val'), 'true'); trPr.append(h)


def no_split(row):
    trPr = row._tr.get_or_add_trPr(); c = OxmlElement('w:cantSplit'); c.set(qn('w:val'), 'true'); trPr.append(c)


def table(headers, rows, ws, head_fill='2F4A6D', size=10, lock_col=None):
    t = doc.add_table(rows=1, cols=len(headers)); borders(t)
    for i, h in enumerate(headers):
        cell_text(t.rows[0].cells[i], h, True, size, RGBColor(0xFF, 0xFF, 0xFF), C); shade(t.rows[0].cells[i], head_fill)
    repeat_header(t.rows[0])
    for r in rows:
        cells = t.add_row().cells
        for i, v in enumerate(r): cell_text(cells[i], v, False, size)
    widths(t, ws); doc.add_paragraph().paragraph_format.space_after = Pt(2)
    return t


