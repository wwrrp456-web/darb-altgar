def rtl_par(p, align=WD_ALIGN_PARAGRAPH.RIGHT):
    pPr = p._p.get_or_add_pPr(); b = OxmlElement('w:bidi'); pPr.append(b); p.alignment = align


def run(p, text, bold=False, size=None, color=None, italic=False):
    r = p.add_run(text); r.bold = bold; r.italic = italic
    r.font.name = FONT; r._element.rPr.rFonts.set(qn('w:cs'), FONT)
    rPr = r._element.get_or_add_rPr(); rtl = OxmlElement('w:rtl'); rPr.append(rtl)
    if size: r.font.size = Pt(size)
    if color is not None: r.font.color.rgb = color
    return r


def para(text='', bold=False, size=None, color=None, after=4, align=WD_ALIGN_PARAGRAPH.RIGHT, italic=False):
    p = doc.add_paragraph(); rtl_par(p, align); p.paragraph_format.space_after = Pt(after)
    if text: run(p, text, bold, size, color, italic)
    return p


def heading(text, level=1):
    size = {1: 17, 2: 14, 3: 12}[level]
    p = para(text, True, size, NAVY if level < 3 else MINT, after=6)
    p.paragraph_format.space_before = Pt(10 if level > 1 else 6); p.paragraph_format.keep_with_next = True
    return p


def shade(cell, hexcolor):
    tcPr = cell._tc.get_or_add_tcPr(); sh = OxmlElement('w:shd'); sh.set(qn('w:val'), 'clear'); sh.set(qn('w:color'), 'auto'); sh.set(qn('w:fill'), hexcolor); tcPr.append(sh)


def borders(tbl, color='B7C3CC'):
    tblPr = tbl._tbl.tblPr; b = OxmlElement('w:tblBorders')
    for e in ('top', 'left', 'bottom', 'right', 'insideH', 'insideV'):
        x = OxmlElement('w:' + e); x.set(qn('w:val'), 'single'); x.set(qn('w:sz'), '4'); x.set(qn('w:space'), '0'); x.set(qn('w:color'), color); b.append(x)
    tblPr.append(b)
    v = OxmlElement('w:bidiVisual'); tblPr.append(v)


def cell_text(cell, text, bold=False, size=10.5, color=None):
    cell.text = ''
    lines = text if isinstance(text, list) else [text]
    first = True
    for ln in lines:
        p = cell.paragraphs[0] if first else cell.add_paragraph(); first = False
        rtl_par(p); p.paragraph_format.space_after = Pt(2)
        run(p, ln, bold, size, color)


def table(rows, widths=(3.4, 13.6), head=None):
    t = doc.add_table(rows=0, cols=len(widths)); t.alignment = WD_TABLE_ALIGNMENT.CENTER; borders(t)
    if head:
        r = t.add_row().cells
        for i, h in enumerate(head):
            cell_text(r[i], h, True, 10.5, RGBColor(255, 255, 255)); shade(r[i], '2F4A6D')
    for row in rows:
        r = t.add_row().cells
        for i, v in enumerate(row):
            cell_text(r[i], v, bold=(i == 0 and len(widths) == 2), size=10.5)
            if i == 0 and len(widths) == 2: shade(r[i], 'F1F4F2')
    for row in t.rows:
        for i, w in enumerate(widths): row.cells[i].width = Cm(w)
    doc.add_paragraph().paragraph_format.space_after = Pt(2)
    return t


